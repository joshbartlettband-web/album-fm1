"""Album's own beats, made in the beat maker, into the firmware: every album/beats/*.json, in name order, after the
library's (dsp/beats.h). SEQ held and PRESET picks them as it picks the library's.

  tools/beats.py --out GEN/beats_mine.h

A beat file (what the beat maker saves; checked here, and a bad one stops the build with the reason):
  {"name": "NIGHT DRIVE",            16 characters at most: A-Z, 0-9, space, - . ' &
   "bpm": 92,                        40..200
   "swing": 0.2,                     0..0.5 (optional): the off sixteenths late by this share of a sixteenth
   "tone": 3000,                     300..9000 Hz (optional): the kit's low-pass, how muffled
   "send": 0.4,                      0..1 (optional): how much goes into the reverse reverb
   "level": 0.9,                     0.2..1.2 (optional)
   "brush": false,                   (optional) the snare a brush
   "kick": "x.......x.x.....",       each drum one bar of 16 sixteenths: "." rest, "-" soft, "o" medium, "x" full;
   "snare": "....o.......o...",      any of kick, snare, hat, open, tom, rim may be left out
   "fill": "....x.....x.xxxx"}       (optional) the snare in every fourth bar"""
import json
import re
import sys
from pathlib import Path

DRUMS = ("kick", "snare", "hat", "open", "tom", "rim", "fill")
NAME = re.compile(r"^[A-Z0-9 \-.'&]{1,16}$")
STEPS = re.compile(r"^[.\-ox]{16}$")


def num(b, k, lo, hi, default, f):
    v = b.get(k, default)
    if not isinstance(v, (int, float)) or isinstance(v, bool) or not lo <= v <= hi:
        raise SystemExit(f"beats: {f}: {k} must be a number from {lo} to {hi}, not {v!r}")
    return float(v)


def c_str(s):
    return "NULL" if s is None else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def beat(f):
    try:
        b = json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise SystemExit(f"beats: {f}: not JSON ({e})")
    if not isinstance(b, dict):
        raise SystemExit(f"beats: {f}: not a beat")
    name = str(b.get("name", "")).strip().upper()
    if not NAME.match(name):
        raise SystemExit(f"beats: {f}: the name must be 1 to 16 characters of A-Z, 0-9, space - . ' &: {name!r}")
    out = {"name": name, "bpm": num(b, "bpm", 40, 200, None, f), "swing": num(b, "swing", 0, 0.5, 0, f),
           "tone": num(b, "tone", 300, 9000, 3000, f), "send": num(b, "send", 0, 1, 0.35, f),
           "level": num(b, "level", 0.2, 1.2, 0.9, f), "brush": 1 if b.get("brush") else 0}
    any_hit = False
    for d in DRUMS:
        s = b.get(d)
        if s in (None, ""):
            out[d] = None
            continue
        s = str(s).lower()
        if not STEPS.match(s):
            raise SystemExit(f"beats: {f}: {d} must be 16 of . - o x, not {s!r}")
        out[d] = None if set(s) == {"."} else s
        any_hit |= out[d] is not None and d != "fill"
    if not any_hit:
        raise SystemExit(f"beats: {f}: no drum plays")
    return out


def main():
    if len(sys.argv) != 3 or sys.argv[1] != "--out":
        raise SystemExit(__doc__)
    beats = [beat(f) for f in sorted(Path("beats").glob("*.json"))]
    names = [b["name"] for b in beats]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise SystemExit(f"beats: two beats are called {', '.join(sorted(dup))}")
    lines = ["/* generated by tools/beats.py from album/beats/*.json: the beats made in the beat maker */",
             "static const beat_entry_t BEATS_MINE[] = {"]
    for b in beats:
        drums = ", ".join(f".{d} = {c_str(b[d])}" for d in DRUMS if b[d])
        fl = {k: f"{float(b[k])!r}f" for k in ("bpm", "swing", "tone", "send", "level")}   # (always a decimal point)
        lines.append(f'    {{{c_str(b["name"])}, {{.bpm = {fl["bpm"]}, .swing = {fl["swing"]}, .tone = {fl["tone"]}, '
                     f'.send = {fl["send"]}, .level = {fl["level"]}, .brush = {b["brush"]}, {drums}}}}},')
    if not beats:
        lines.append('    {"", {.bpm = 90.0f}},          /* (none yet: a C array is never empty) */')
    lines += ["};", f"#define BEATS_MINE_N {len(beats)}u", ""]
    Path(sys.argv[2]).write_text("\n".join(lines))
    print(f"beats: {len(beats)} of your own" + (f": {', '.join(names)}" if names else ""))


if __name__ == "__main__":
    main()
